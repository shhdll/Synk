// Reads android/local.properties, which is git-ignored and therefore the right
// home for the Google Maps SDK key. The key reaches AndroidManifest.xml as a
// manifest placeholder, so it never appears in a committed file.
//
// Every developer adds their own line:  MAPS_API_KEY=...
// If the line is missing the build still succeeds and the map renders blank,
// which is the clearest signal that the key was not set.
val localProperties = Properties()
val localPropertiesFile = rootProject.file("local.properties")
if (localPropertiesFile.exists()) {
    localPropertiesFile.inputStream().use { localProperties.load(it) }
}
val mapsApiKey: String = localProperties.getProperty("MAPS_API_KEY") ?: ""

